"""Regenerate configs/template.yaml (every config key with its default and help text).

    python tools/make_config_template.py
"""
import os
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

try:
	import yaml
	import config
	import predictor_main
	import shap_explain
except ImportError as e:
	sys.exit(f"{e}\nRun this with the project's environment (pip install -r requirements.txt), "
		"e.g. apptainer exec --nv ts-forecaster.sif python3 tools/make_config_template.py")

SECTION_INTRO = {
	"run": "What to run and where results go.",
	"data": "Input file and the forecasting task.",
	"preprocessing": "Gap filling, scaling and oversampling (fitted on the training period only).",
	"model": "Model architecture.",
	"training": "Optimisation and hardware.",
	"evaluation": "Scores written to results.csv.",
	"tuning": "Optuna hyperparameter search (run.py --mode tune).",
	"explain": "SHAP explanations of a saved model (run.py --mode explain / shap_explain.py).",
}
# placeholders shown instead of the parser default
SHOWN = {
	("run", "name"): "my_experiment",
	("data", "file"): "data/air_quality/Nongzhanguan.parquet",
	("tuning", "search_space"): "configs/optuna_search_space.json",
}


def actions_by_dest(parser):
	return {a.dest: a for a in parser._actions}


def yaml_value(value):
	text = yaml.safe_dump(value, default_flow_style=True).strip()
	return text[:-4].strip() if text.endswith("...") else text


def render():
	main_actions = actions_by_dest(predictor_main.build_parser())
	shap_actions = actions_by_dest(shap_explain.build_parser())
	alias = {dest: key for (section, key), dest in config.ALIASES.items()}
	lines = [
		"# ts-forecaster configuration template: every setting with its default.",
		"# Copy this file, keep the sections/keys you want to change and delete the rest",
		"# (anything left out uses the default). Run it with",
		"#     python run.py --config my_config.yaml",
		"# Options given on the command line override the file. Generated by",
		"# tools/make_config_template.py from the option help texts.",
		"",
	]
	for section, dests in config.ALL_SECTIONS.items():
		lines += [f"{section}:", f"  # {SECTION_INTRO.get(section, '')}"]
		actions = shap_actions if section in config.EXPLAIN_SECTIONS else main_actions
		for dest in dests:
			action = actions.get(dest)
			key = alias.get(dest, dest)
			if action is None:
				continue
			default = SHOWN.get((section, key), action.default)
			if default is not None and isinstance(default, str) and default.lower() in ("true", "false"):
				default = default.lower() == "true"
			help_text = (action.help or "").replace("%(default)s", str(action.default))
			for line in textwrap.wrap(help_text, width=86):
				lines.append(f"  # {line}")
			lines.append(f"  {key}: {yaml_value(default)}")
		lines.append("")
	return "\n".join(lines)


TEMPLATE = os.path.join(ROOT, "configs", "template.yaml")


def main():
	with open(TEMPLATE, "w") as f:
		f.write(render())
	print(f"wrote {TEMPLATE}")


if __name__ == "__main__":
	main()
